Baker_cuda_oss::Baker_cuda_oss(
    const Baker_module_impl           *baker_module,
    int                                dev_id,
    mi::neuraylib::ITarget_code const *target_code,
    mi::neuraylib::ICanvas            *texture,
    unsigned int                       samples,
    mi::Float32                        min_u,
    mi::Float32                        max_u,
    mi::Float32                        min_v,
    mi::Float32                        max_v,
    mi::Float32                        animation_time,
    float                             *constant_target,
    unsigned int                       constant_target_components,
    unsigned int                       state_flags,
    bool                               is_environment,
    bool                               want_constant_detection)
  : m_target_code(target_code, mi::base::DUP_INTERFACE),
    m_texture(texture, mi::base::DUP_INTERFACE),
    m_samples(samples),
    m_min_u(min_u),
    m_max_u(max_u),
    m_min_v(min_v),
    m_max_v(max_v),
    m_animation_time(animation_time),
    m_constant_target(constant_target),
    m_constant_target_components(constant_target_components),
    m_state_flags(state_flags),
    m_is_environment(is_environment),
    m_want_constant_detection(want_constant_detection)
{
    // Resolve / cache the per-device CUDA context. baker_module owns the
    // cache and the Cuda_dynload — we just push the context.
    CUcontext ctx = baker_module->get_dev_context_oss(dev_id);
    if (!ctx) {
        log_debug("Baker_cuda_oss: failed to obtain CUDA context.");
        return;
    }
    if (cuCtxPushCurrent(ctx) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuCtxPushCurrent failed.");
        return;
    }
    m_pushed_ctx = ctx;

    // Validate the device id before marking ready; the compute-capability
    // check was already performed by ensure_cuda_loaded_oss().
    CUdevice device = 0;
    if (cuDeviceGet(&device, dev_id) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuDeviceGet failed.");
        return;
    }
    m_ready = true;
}

Baker_cuda_oss::~Baker_cuda_oss()
{
    if (m_pushed_ctx) {
        CUcontext popped = nullptr;
        cuCtxPopCurrent(&popped);
    }
}

bool Baker_cuda_oss::bake_texture(DB::Transaction* transaction)
{
    if (!m_ready) return false;
    m_all_pixels_equal = false;

    // ---- Discover canvas geometry and pixel-type metadata ----
    unsigned tex_w = 1, tex_h = 1;
    unsigned n_components = m_constant_target_components;
    IMAGE::Pixel_type pixel_type = IMAGE::PT_UNDEF;
    mi::base::Handle<mi::neuraylib::ITile> tile;
    if (m_texture) {
        tex_w = m_texture->get_resolution_x();
        tex_h = m_texture->get_resolution_y();
        pixel_type = IMAGE::convert_pixel_type_string_to_enum(m_texture->get_type());
        if (pixel_type == IMAGE::PT_UNDEF) {
            log_debug("Baker_cuda_oss: unknown canvas pixel type.");
            return false;
        }
        if (pixel_type == IMAGE::PT_SINT8 || pixel_type == IMAGE::PT_RGBE
            || pixel_type == IMAGE::PT_FLOAT32) {
            n_components = 1;
        } else if (pixel_type == IMAGE::PT_FLOAT32_2) {
            n_components = 2;
        } else if (pixel_type == IMAGE::PT_FLOAT32_3 || pixel_type == IMAGE::PT_RGB_FP) {
            n_components = 3;
        } else if (pixel_type == IMAGE::PT_FLOAT32_4 || pixel_type == IMAGE::PT_COLOR) {
            n_components = 4;
        } else {
            // Results are written via ITile::set_pixel, which converts to any
            // canvas pixel type; n_components is only the constant-detection width.
            n_components = IMAGE::get_components_per_pixel(pixel_type);
        }
        tile = m_texture->get_tile();
    } else {
        pixel_type = IMAGE::PT_FLOAT32_4;  // unused; constant path writes raw floats
    }

    const float du = (float)(1.0 / (double)tex_w);
    const float dv = (float)(1.0 / (double)tex_h);

    // ---- Link kernel PTX + MDL PTX into a single module ----
    Scoped_module module;
    if (!link_and_load_module(m_target_code.get(), module))
        return false;

    // ---- Resolve kernel entry point and tex_vtable address ----
    CUfunction  f_bake   = nullptr;
    CUdeviceptr d_vtable = 0;
    if (!resolve_kernel(module.handle, m_is_environment, f_bake, d_vtable))
        return false;

    // ---- Upload textures (descriptors + flat per-tile / per-frame arrays) ----
    Scoped_tex_resources tex_res;
    Scoped_dptr d_tiles, d_frames, d_descs, d_handler;
    if (!upload_texture_handler(transaction, m_target_code.get(), d_vtable,
                                tex_res, d_tiles, d_frames, d_descs, d_handler))
        return false;

    // ---- Upload Bake_params_oss ----
    Bake_params_oss h_params = {
        tex_w, tex_h, m_samples, m_state_flags,
        (unsigned)(m_is_environment ? 1u : 0u),
        (unsigned)(pixel_type == IMAGE::PT_SINT8 ? 1u : 0u),
        du, dv, m_min_u, m_max_u, m_min_v, m_max_v,
        m_animation_time
    };
    Scoped_dptr d_params;
    if (!gpu_dup(d_params, &h_params, sizeof(h_params)))
        return false;

    // ---- Upload captured arguments (may be null) ----
    Scoped_dptr d_args;
    mi::base::Handle<const mi::neuraylib::ITarget_argument_block> args(
        m_target_code->get_argument_block(0));
    if (args && !gpu_dup(d_args, args->get_data(), args->get_size()))
        return false;

    // ---- Allocate result buffer (always float4 per pixel) ----
    const size_t pixel_count = (size_t)tex_w * (size_t)tex_h;
    const size_t result_bytes = pixel_count * sizeof(float4);
    Scoped_dptr d_results;
    if (cuMemAlloc(&d_results.p, result_bytes) != CUDA_SUCCESS)
        return false;

    // ---- Launch ----
    TIME::Stopwatch sw_kernel;
    sw_kernel.start();

    const unsigned int block_x = 16, block_y = 16;
    const unsigned int grid_x = (tex_w + block_x - 1) / block_x;
    const unsigned int grid_y = (tex_h + block_y - 1) / block_y;

    void* kernel_args[] = {
        &d_results.p,
        &d_params.p,
        &d_args.p,
        &d_handler.p
    };
    CUresult launch_res = cuLaunchKernel(
        f_bake,
        grid_x, grid_y, 1,
        block_x, block_y, 1,
        0, nullptr,
        kernel_args, nullptr);
    if (launch_res == CUDA_SUCCESS) {
        launch_res = cuStreamSynchronize(nullptr);
    }

    sw_kernel.stop();

    if (launch_res != CUDA_SUCCESS) {
        const char* err = nullptr;
        cuGetErrorString(launch_res, &err);
        log_debug("Baker_cuda_oss: kernel launch/sync failed: %s",
                  err ? err : "<unknown>");
        return false;
    }
    log_debug("Baker_cuda_oss execution time: %1.0f ms", sw_kernel.elapsed() * 1000);

    // ---- Read back and write canvas/constant target ----
    std::vector<float4> readback(pixel_count);
    if (cuMemcpyDtoH(readback.data(), d_results.p, result_bytes) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuMemcpyDtoH failed.");
        return false;
    }

    if (m_texture) {
        // Mirrors the CPU loop's per-pixel write in
        // Baker_fragmented_job::execute_fragment: scrub NaN, then hand the
        // cleaned floats to the canonical IMAGE encoder via ITile::set_pixel
        // (which handles RGBE/FLOAT*/COLOR conversion for us).
        auto clean = [](float v) { return (v != v) ? 0.0f : v; };
        for (size_t i = 0; i < pixel_count; ++i) {
            mi::Float32 v[4] = { clean(readback[i].x), clean(readback[i].y),
                                 clean(readback[i].z), clean(readback[i].w) };
            if (pixel_type == IMAGE::PT_SINT8) {
                // Majority-vote bool, encoded so set_pixel<PT_SINT8> yields
                // byte 1/0 (matches the CPU path in baker.cpp).
                const float bv = (v[0] > 0.5f) ? (1.0f / 255.0f) : 0.0f;
                v[0] = v[1] = v[2] = bv;
            }
            tile->set_pixel((mi::Uint32)(i % tex_w), (mi::Uint32)(i / tex_w), v);
        }
    } else {
        // Constant target: a single pixel of n_components floats.
        const float r[4] = {
            readback[0].x, readback[0].y, readback[0].z, readback[0].w
        };
        for (unsigned c = 0; c < m_constant_target_components; ++c)
            m_constant_target[c] = (r[c] != r[c]) ? 0.0f : r[c];
    }
    if (m_want_constant_detection) {
        m_all_pixels_equal = are_all_pixels_equal_host(
            readback.data(), pixel_count, n_components);
    }
    return true;
}

