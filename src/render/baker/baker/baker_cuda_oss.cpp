// Upload a single uv-tile mipmap (level 0) as a pair of CUDA texture objects.
// `effective_gamma` linearises the data (see note below). On a hard CUDA error
// returns false; for soft issues (no canvas / zero size) leaves `out` zeroed
// and returns true (so the tile reads back as black / invalid).
bool upload_tile_canvas(
    IMAGE::Image_module          *image_module,
    const mi::neuraylib::ICanvas *canvas_in,
    mi::Float32                   effective_gamma,
    Scoped_tex_resources         &res,
    Texture                      &out)
{
    out = Texture();
    if (!canvas_in) return true;

    const unsigned tex_w = canvas_in->get_resolution_x();
    const unsigned tex_h = canvas_in->get_resolution_y();
    if (tex_w == 0 || tex_h == 0) return true;

    // Convert to RGBA float. This is required, not just convenient: the
    // device side creates the cudaArray with a 4x32-bit-float channel
    // descriptor (see below) and every device lookup reads a float4, so the
    // host upload must be RGBA float32. The baker is not performance-critical,
    // so the four-channel cost over single/three-channel inputs is fine and
    // keeps every tile a uniform representation.
    mi::base::Handle<mi::neuraylib::ICanvas> rgba_canvas(
        image_module->convert_canvas(canvas_in, IMAGE::PT_COLOR));
    if (!rgba_canvas) return true;

    // Linearise. With tex_lookup_call_mode = "vtable" the MDL-emitted PTX
    // expects texture data to already be in linear color space — the
    // built-in CPU runtime handles this transparently, but the vtable
    // runtime in texture_support_cuda.h does NOT. If we skipped this the
    // GPU bake would come out brighter than the CPU bake for any sRGB or
    // gamma-2.2 input texture.
    if (effective_gamma > 0.0f && effective_gamma != 1.0f) {
        rgba_canvas->set_gamma(effective_gamma);
        image_module->adjust_gamma(rgba_canvas.get(), /*new_gamma=*/1.0f);
    }

    mi::base::Handle<const mi::neuraylib::ITile> tile(rgba_canvas->get_tile());
    const void* pixels = tile->get_data();

    cudaChannelFormatDesc fmt;
    fmt.x = 32; fmt.y = 32; fmt.z = 32; fmt.w = 32;
    fmt.f = cudaChannelFormatKindFloat;

    cudaArray_t array = nullptr;
    if (cudaMallocArray(&array, &fmt, tex_w, tex_h, 0) != cudaSuccess || !array) {
        log_debug("Baker_cuda_oss: cudaMallocArray failed.");
        return false;
    }
    res.arrays.push_back(array);
    const size_t row_bytes = (size_t)tex_w * 4u * sizeof(float);
    if (cudaMemcpy2DToArray(array, 0, 0, pixels, row_bytes, row_bytes, tex_h,
                                cudaMemcpyHostToDevice) != cudaSuccess) {
        log_debug("Baker_cuda_oss: cudaMemcpy2DToArray failed.");
        return false;
    }

    cudaResourceDesc res_desc = {};
    res_desc.resType = cudaResourceTypeArray;
    res_desc.res.array.array = array;

    cudaTextureDesc tdesc_f = {};
    tdesc_f.addressMode[0] = cudaAddressModeWrap;
    tdesc_f.addressMode[1] = cudaAddressModeWrap;
    tdesc_f.filterMode = cudaFilterModeLinear;
    tdesc_f.readMode = cudaReadModeElementType;
    tdesc_f.normalizedCoords = 1;

    if (cudaCreateTextureObject(&out.filtered_object, &res_desc, &tdesc_f, nullptr)
        != cudaSuccess) {
        log_debug("Baker_cuda_oss: cudaCreateTextureObject(filtered) failed.");
        return false;
    }
    res.tex_objects.push_back(out.filtered_object);

    cudaTextureDesc tdesc_u = tdesc_f;
    tdesc_u.filterMode = cudaFilterModePoint;
    tdesc_u.addressMode[0] = cudaAddressModeBorder;
    tdesc_u.addressMode[1] = cudaAddressModeBorder;
    tdesc_u.normalizedCoords = 0;
    if (cudaCreateTextureObject(&out.unfiltered_object, &res_desc, &tdesc_u, nullptr)
        != cudaSuccess) {
        log_debug("Baker_cuda_oss: cudaCreateTextureObject(unfiltered) failed.");
        return false;
    }
    res.tex_objects.push_back(out.unfiltered_object);

    out.size = make_uint3(tex_w, tex_h, 1u);
    out.inv_size = make_float3(1.0f / (float)tex_w, 1.0f / (float)tex_h, 1.0f);
    return true;
}

// Build the descriptor for a 2D MDL texture referenced by the target code at
// index `tex_idx`, uploading every animation frame and every uv-tile. Per-tile
// `Texture` entries are appended to `host_tiles` (their absolute index is
// recorded in the per-frame grid's tile_offset); per-frame `Tex_frame`
// entries are appended to `host_frames` (the desc's frame range starts at
// `out_frame_base`). The desc's `frames`/`tiles` device pointers are patched
// by the caller after the flat arrays are uploaded.
//
// Non-2D textures (3D, cube) produce an invalid descriptor (is_valid == 0) so
// material lookups against them return the MDL "invalid texture" sentinel.
// Returns false only on a hard CUDA error.
bool upload_one_texture(
    DB::Transaction                   *transaction,
    mi::neuraylib::ITarget_code const *target_code,
    mi::Size                           tex_idx,
    Scoped_tex_resources              &res,
    std::vector<Texture>              &host_tiles,
    std::vector<Tex_frame>            &host_frames,
    Texture_desc                      &out_desc,
    mi::Size                          &out_frame_base)
{
    std::memset(&out_desc, 0, sizeof(out_desc));
    out_desc.is_valid = 0;
    out_frame_base = host_frames.size();

    const mi::neuraylib::ITarget_code::Texture_shape shape =
        target_code->get_texture_shape(tex_idx);
    if (shape != mi::neuraylib::ITarget_code::Texture_shape_2d) {
        log_debug("Baker_cuda_oss: skipping non-2D texture at index %u "
                  "(shape=%d) — material lookup will return invalid.",
                  (unsigned)tex_idx, (int)shape);
        return true;
    }

    // Resolve the DB texture and its image.
    const char* db_name = target_code->get_texture(tex_idx);
    if (!db_name) return true;
    DB::Tag tag = transaction->name_to_tag(db_name);
    if (!tag) return true;
    if (transaction->get_class_id(tag) != TEXTURE::ID_TEXTURE) return true;
    DB::Access<TEXTURE::Texture> tex(tag, transaction);
    DB::Tag image_tag = tex->get_image();
    if (!image_tag) return true;
    DB::Access<DBIMAGE::Image> image(image_tag, transaction);

    SYSTEM::Access_module<IMAGE::Image_module> image_module(false);

    const bool     is_uvtile  = image->is_uvtile();
    const mi::Size num_frames = image->get_length();   // never zero
    if (num_frames == 0) return true;

    for (mi::Size f = 0; f < num_frames; ++f) {
        const mi::Size frame_number = image->get_frame_number(f);

        mi::Sint32 min_u = 0, min_v = 0, max_u = 0, max_v = 0;
        image->get_uvtile_uv_ranges(f, min_u, min_v, max_u, max_v);
        const mi::Uint32 count_u = (mi::Uint32)(max_u - min_u + 1);
        const mi::Uint32 count_v = (mi::Uint32)(max_v - min_v + 1);

        // Allocate (and zero) the bounding-rectangle grid for this frame.
        // Missing tiles stay zero -> read back as black on the device.
        const mi::Size grid_base = host_tiles.size();
        host_tiles.resize(grid_base + (size_t)count_u * count_v);

        const mi::Size n_tiles = image->get_frame_length(f);
        for (mi::Size i = 0; i < n_tiles; ++i) {
            mi::Sint32 u = 0, v = 0;
            if (image->get_uvtile_uv(f, i, u, v) != 0)
                continue;  // out-of-bounds uvtile id; leave slot black
            const mi::Size slot =
                (mi::Size)(v - min_v) * count_u + (mi::Size)(u - min_u);

            mi::base::Handle<const IMAGE::IMipmap> mipmap(
                image->get_mipmap(transaction, f, i));
            if (!mipmap) continue;
            mi::base::Handle<const mi::neuraylib::ICanvas> canvas(mipmap->get_level(0));

            const mi::Float32 gamma = tex->get_effective_gamma(transaction, f, i);
            if (!upload_tile_canvas(image_module.get(), canvas.get(), gamma,
                                    res, host_tiles[grid_base + slot]))
                return false;
        }

        Tex_frame fr;
        fr.frame_number   = (uint32_t)frame_number;
        fr.grid.min_u     = min_u;
        fr.grid.min_v     = min_v;
        fr.grid.count_u   = count_u;
        fr.grid.count_v   = count_v;
        fr.grid.tile_offset = (uint32_t)grid_base;
        host_frames.push_back(fr);
    }

    out_desc.is_valid    = 1;
    out_desc.is_uvtile   = is_uvtile ? 1u : 0u;
    out_desc.num_frames  = (uint32_t)num_frames;
    out_desc.first_frame = host_frames[out_frame_base].frame_number;
    out_desc.last_frame  = host_frames.back().frame_number;
    // frames / tiles device pointers are patched by the caller.
    return true;
}

