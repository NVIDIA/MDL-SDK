bool are_all_pixels_equal_host(
    const float4* pixels,
    size_t        count,
    unsigned      num_components)
{
    if (count == 0) return true;
    constexpr float eps = 1e-7f;
    const float4 first = pixels[0];
    for (size_t i = 1; i < count; ++i) {
        if (num_components >= 1 && fabsf(pixels[i].x - first.x) > eps) return false;
        if (num_components >= 2 && fabsf(pixels[i].y - first.y) > eps) return false;
        if (num_components >= 3 && fabsf(pixels[i].z - first.z) > eps) return false;
        if (num_components >= 4 && fabsf(pixels[i].w - first.w) > eps) return false;
    }
    return true;
}

// ----------------------------------------------------------------------------
// Scope guards for the CUDA resources used by one bake. They make every error
// path in bake_texture() a plain `return false` — all cleanup is implicit and
// runs in reverse declaration order.
// ----------------------------------------------------------------------------

// Owns one device allocation.
struct Scoped_dptr {
    Scoped_dptr() = default;
    ~Scoped_dptr() { if (p) cuMemFree(p); }
    Scoped_dptr(const Scoped_dptr&) = delete;
    Scoped_dptr& operator=(const Scoped_dptr&) = delete;

    CUdeviceptr p = 0;
};

// Owns a CUDA JIT link state. The state also owns the cubin returned by
// cuLinkComplete, so it must stay alive until cuModuleLoadDataEx has run.
struct Scoped_link_state {
    Scoped_link_state() = default;
    ~Scoped_link_state() { if (state) cuLinkDestroy(state); }
    Scoped_link_state(const Scoped_link_state&) = delete;
    Scoped_link_state& operator=(const Scoped_link_state&) = delete;

    CUlinkState state = nullptr;
};

// Owns a loaded CUDA module.
struct Scoped_module {
    Scoped_module() = default;
    ~Scoped_module() { if (handle) cuModuleUnload(handle); }
    Scoped_module(const Scoped_module&) = delete;
    Scoped_module& operator=(const Scoped_module&) = delete;

    CUmodule handle = nullptr;
};

// Owns the CUDA arrays and texture objects backing the uploaded textures.
// Texture objects are destroyed before the arrays they reference.
struct Scoped_tex_resources {
    Scoped_tex_resources() = default;
    ~Scoped_tex_resources() {
        for (cudaTextureObject_t t : tex_objects) cudaDestroyTextureObject(t);
        for (cudaArray_t a : arrays)              cudaFreeArray(a);
    }
    Scoped_tex_resources(const Scoped_tex_resources&) = delete;
    Scoped_tex_resources& operator=(const Scoped_tex_resources&) = delete;

    std::vector<cudaArray_t>         arrays;
    std::vector<cudaTextureObject_t> tex_objects;
};

// Allocates device memory into `out` and copies `bytes` from `src`.
bool gpu_dup(Scoped_dptr &out, const void *src, size_t bytes)
{
    if (cuMemAlloc(&out.p, bytes) != CUDA_SUCCESS) {
        out.p = 0;
        return false;
    }
    return cuMemcpyHtoD(out.p, src, bytes) == CUDA_SUCCESS;
}

