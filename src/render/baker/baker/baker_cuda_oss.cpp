// JIT-link the embedded baker kernel PTX with the MDL-generated PTX and load
// the result as a module.
bool link_and_load_module(
    mi::neuraylib::ITarget_code const *target_code,
    Scoped_module                     &out_module)
{
    TIME::Stopwatch sw_link;
    sw_link.start();

    Scoped_link_state link;
    if (cuLinkCreate(0, nullptr, nullptr, &link.state) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuLinkCreate failed.");
        return false;
    }

    // cuLinkAddData() treats CU_JIT_INPUT_PTX as a NUL-terminated C string and
    // scans past `size` until a NUL — so the data MUST be NUL-terminated and the
    // size must include the terminator. The embedded g_baker_kernel_oss_ptx[]
    // array (from bin2c.py) is NOT NUL-terminated, so pass a terminated copy
    // (size + 1). Without this, ptxas ingests whatever bytes follow the array in
    // memory and the JIT link fails.
    const std::string kernel_ptx(
        reinterpret_cast<const char*>(g_baker_kernel_oss_ptx),
        g_baker_kernel_oss_ptx_len);
    if (cuLinkAddData(
            link.state, CU_JIT_INPUT_PTX,
            (void*)kernel_ptx.c_str(), kernel_ptx.size() + 1,
            "baker_kernel_oss.ptx", 0, nullptr, nullptr) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuLinkAddData (kernel) failed.");
        return false;
    }
    if (cuLinkAddData(
            link.state, CU_JIT_INPUT_PTX,
            (void*)target_code->get_code(),
            target_code->get_code_size(),
            "mdl_lambda.ptx", 0, nullptr, nullptr) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuLinkAddData (MDL lambda) failed.");
        return false;
    }

    void*  cubin     = nullptr;
    size_t cubin_len = 0;
    if (cuLinkComplete(link.state, &cubin, &cubin_len) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuLinkComplete failed.");
        return false;
    }
    // `link` owns the cubin buffer, so the module is loaded before it goes
    // out of scope.
    if (cuModuleLoadDataEx(&out_module.handle, cubin, 0, nullptr, nullptr)
        != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuModuleLoadDataEx failed.");
        return false;
    }

    sw_link.stop();
    log_debug("Baker_cuda_oss linking time: %1.0f ms", sw_link.elapsed() * 1000);
    return true;
}

// Resolve the bake kernel entry point and the device address of the texture
// runtime's vtable. The kernel exposes a stable C-linkage pointer variable
// holding the address of tex_vtable — the unmangled name of `tex_vtable`
// itself depends on the C++ ABI, so the pointer indirection is reliable.
bool resolve_kernel(
    CUmodule      module,
    bool          is_environment,
    CUfunction   &out_bake,
    CUdeviceptr  &out_vtable)
{
    const char* entry = is_environment ? "bake_environment" : "bake_surface";
    if (cuModuleGetFunction(&out_bake, module, entry) != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuModuleGetFunction(%s) failed.", entry);
        return false;
    }

    CUdeviceptr d_vtable_ptr_var = 0;
    size_t      vtable_ptr_var_size = 0;
    if (cuModuleGetGlobal(
            &d_vtable_ptr_var, &vtable_ptr_var_size, module,
            "baker_oss_tex_vtable_addr") != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuModuleGetGlobal(baker_oss_tex_vtable_addr) failed.");
        return false;
    }
    void* d_vtable_raw = nullptr;
    if (cuMemcpyDtoH(&d_vtable_raw, d_vtable_ptr_var, sizeof(void*))
        != CUDA_SUCCESS) {
        log_debug("Baker_cuda_oss: cuMemcpyDtoH(vtable address) failed.");
        return false;
    }
    out_vtable = (CUdeviceptr)(uintptr_t)d_vtable_raw;
    return true;
}

// Upload every texture referenced by the target code — the per-texture
// descriptors plus the flat per-tile and per-frame arrays they point into —
// and the Texture_handler tying them together. Index 0 is the MDL "invalid
// texture" and carries no data.
bool upload_texture_handler(
    DB::Transaction                   *transaction,
    mi::neuraylib::ITarget_code const *target_code,
    CUdeviceptr                        d_vtable,
    Scoped_tex_resources              &res,
    Scoped_dptr                       &d_tiles,
    Scoped_dptr                       &d_frames,
    Scoped_dptr                       &d_descs,
    Scoped_dptr                       &d_handler)
{
    std::vector<Texture>      host_tiles;    // flat, absolute tile_offset
    std::vector<Tex_frame>    host_frames;   // flat, sliced per descriptor
    std::vector<Texture_desc> host_descs;
    std::vector<mi::Size>     desc_frame_base;
    const mi::Size num_tex = target_code->get_texture_count();
    if (num_tex > 1) {
        host_descs.reserve(num_tex - 1);
        desc_frame_base.reserve(num_tex - 1);
        for (mi::Size i = 1; i < num_tex; ++i) {
            Texture_desc desc;
            mi::Size frame_base = 0;
            if (!upload_one_texture(transaction, target_code, i, res,
                                    host_tiles, host_frames, desc, frame_base))
                return false;
            host_descs.push_back(desc);
            desc_frame_base.push_back(frame_base);
        }
    }

    if (!host_tiles.empty() &&
        !gpu_dup(d_tiles, host_tiles.data(), host_tiles.size() * sizeof(Texture)))
        return false;
    if (!host_frames.empty() &&
        !gpu_dup(d_frames, host_frames.data(), host_frames.size() * sizeof(Tex_frame)))
        return false;

    for (size_t k = 0; k < host_descs.size(); ++k) {
        // tile_offset values are absolute into host_tiles, so the global base
        // pointer is correct for every descriptor.
        host_descs[k].tiles  = (Texture const*)d_tiles.p;
        host_descs[k].frames = (Tex_frame const*)(
            d_frames.p + desc_frame_base[k] * sizeof(Tex_frame));
    }
    if (!host_descs.empty() &&
        !gpu_dup(d_descs, host_descs.data(), host_descs.size() * sizeof(Texture_desc)))
        return false;

    Texture_handler host_handler = {};
    host_handler.vtable        = reinterpret_cast<mi::neuraylib::Texture_handler_vtable const*>(d_vtable);
    host_handler.num_textures  = host_descs.size();
    host_handler.texture_descs = (Texture_desc const*)d_descs.p;
    host_handler.num_mbsdfs    = 0;
    host_handler.mbsdfs        = nullptr;
    host_handler.num_lightprofiles = 0;
    host_handler.lightprofiles     = nullptr;
    return gpu_dup(d_handler, &host_handler, sizeof(host_handler));
}

